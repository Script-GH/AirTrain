function series(n: number, start: number, end: number, jitter = 0): number[] {
  const out: number[] = [];
  for (let i = 0; i < n; i++) {
    const t = n === 1 ? 1 : i / (n - 1);
    const base = start + (end - start) * t;
    const wiggle = jitter === 0 ? 0 : Math.sin(i * 0.7) * jitter;
    out.push(base + wiggle);
  }
  return out;
}

const DEMO_STARTED_OFFSET_MS = 59_000;

export function demoJob(now = Date.now()): Job {
  const acc: number[] = [];
  const loss: number[] = [];
  const log: RoundLog[] = [];
  for (let r = 1; r <= 14; r++) {
    const a = 0.86 * (1 - Math.exp(-r / 10));
    const l = 2.3 * Math.exp(-r / 12) + 0.35;
    acc.push(a);
    loss.push(l);
    log.unshift({ round: r, acc: a, loss: l, devices: 2, samples: 2100 * r * 4 });
  }
  return {
    round: 14,
    totalRounds: 50,
    acc,
    loss,
    log,
    startedAt: now - DEMO_STARTED_OFFSET_MS,
    throughput: 2400,
  };
}

